from __future__ import annotations

from typing import Any


def _mcq(
    name: str,
    category: str,
    question: str,
    letter: str,
    answer_text: str,
) -> dict[str, Any]:
    """Build a multiple-choice case with letter+text keywords for heuristic score."""
    return {
        "name": name,
        "category": category,
        "question": question,
        "correct_answer": f"{letter}) {answer_text}",
        "keywords": [letter, answer_text],
    }


def _math(
    name: str,
    category: str,
    question: str,
    answer: str,
    *extra_keywords: str,
) -> dict[str, Any]:
    kws = [answer, *extra_keywords]
    return {
        "name": name,
        "category": category,
        "question": question,
        "correct_answer": answer,
        "keywords": list(kws),
    }


def _completion(
    name: str,
    category: str,
    question: str,
    correct: str,
    *keywords: str,
) -> dict[str, Any]:
    return {
        "name": name,
        "category": category,
        "question": question,
        "correct_answer": correct,
        "keywords": list(keywords) if keywords else [correct.split()[0]],
    }


